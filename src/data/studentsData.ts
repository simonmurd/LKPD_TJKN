const STORAGE_KEY = 'tjkn_students_database_v1';
const ACTIVE_STUDENT_KEY = 'tjkn_active_student_session';

export function getAllStudents(): StudentProfile[] {
  if (typeof window === 'undefined') return INITIAL_STUDENTS_LIST;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Failed to parse students from localStorage', e);
  }
  return INITIAL_STUDENTS_LIST;
}

export function saveAllStudents(students: StudentProfile[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(students));
  } catch (e) {
    console.error('Failed to save students', e);
  }
}

export function resetStudentsToDefault(): StudentProfile[] {
  if (typeof window !== 'undefined') {
    localStorage.removeItem(STORAGE_KEY);
  }
  return INITIAL_STUDENTS_LIST;
}

